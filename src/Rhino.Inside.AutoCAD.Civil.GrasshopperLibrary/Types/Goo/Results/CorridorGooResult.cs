using Rhino.Geometry;

namespace Rhino.Inside.AutoCAD.Civil.GrasshopperLibrary;

/// <summary>
/// Represents the result of extracting data from a Civil 3D Corridor.
/// </summary>
public class CorridorGooResult : GooResultBase
{
    /// <summary>
    /// Gets the properties of the Corridor.
    /// </summary>
    public GH_CivilCorridorProperties? PropertiesGoo { get; }

    /// <summary>
    /// Gets the baselines of the Corridor.
    /// </summary>
    public List<GH_CivilCorridorBaseline>? BaselinesGoo { get; }

    /// <summary>
    /// Gets all Baseline Regions from all Baselines.
    /// </summary>
    public List<GH_CivilCorridorBaselineRegion>? RegionsGoo { get; }

    /// <summary>
    /// Gets all Feature Lines from all Baselines.
    /// </summary>
    public List<GH_CivilCorridorFeatureLine>? FeatureLinesGoo { get; }

    /// <summary>
    /// Gets the surfaces generated by the Corridor.
    /// </summary>
    public List<GH_CivilCorridorSurface>? SurfacesGoo { get; }

    /// <summary>
    /// Gets the combined corridor surfaces as a Rhino mesh.
    /// </summary>
    public Mesh? Mesh { get; }

    /// <summary>
    /// Initializes a new instance of the <see cref="CorridorGooResult"/> class.
    /// </summary>
    /// <param name="propertiesGoo">The properties of the Corridor.</param>
    /// <param name="baselinesGoo">The baselines of the Corridor.</param>
    /// <param name="regionsGoo">All Baseline Regions from all Baselines.</param>
    /// <param name="featureLinesGoo">All Feature Lines from all Baselines.</param>
    /// <param name="surfacesGoo">The surfaces generated by the Corridor.</param>
    /// <param name="mesh">The combined corridor surfaces as a Rhino mesh.</param>
    public CorridorGooResult(
        GH_CivilCorridorProperties? propertiesGoo,
        List<GH_CivilCorridorBaseline>? baselinesGoo,
        List<GH_CivilCorridorBaselineRegion>? regionsGoo,
        List<GH_CivilCorridorFeatureLine>? featureLinesGoo,
        List<GH_CivilCorridorSurface>? surfacesGoo,
        Mesh? mesh)
    {
        PropertiesGoo = propertiesGoo;
        BaselinesGoo = baselinesGoo;
        RegionsGoo = regionsGoo;
        FeatureLinesGoo = featureLinesGoo;
        SurfacesGoo = surfacesGoo;
        Mesh = mesh;
    }

    /// <summary>
    /// Gets a failed result instance.
    /// </summary>
    public static CorridorGooResult Failed => new(null, null, null, null, null, null) { IsSuccess = false };
}
